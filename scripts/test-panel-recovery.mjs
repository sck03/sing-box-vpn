import assert from "node:assert/strict";
import { JSDOM } from "jsdom";
import { capabilitiesFixture } from "./panel-fixtures.mjs";
const dom = new JSDOM('<main id="content"></main><dialog id="dialog"></dialog><div id="notice"></div>', { url:"http://localhost/", pretendToBeVisual:true });
for (const name of ["window", "document", "Node", "Event", "FormData"]) globalThis[name] = dom.window[name];
dom.window.HTMLDialogElement.prototype.showModal = function(){this.open=true;};
dom.window.HTMLDialogElement.prototype.close = function(){this.open=false;this.dispatchEvent(new Event("close"));};
globalThis.fetch = async (url) => { if(url === "/api/capabilities") return {ok:true,json:async()=>capabilitiesFixture}; throw Error("Unexpected request "+url); };
const { certificates } = await import("../internal/manage/panel/certificate-page.js");
const { inbounds } = await import("../internal/manage/panel/network.js");
const tasks = [];
const config = {app:{address:"example.test",nodes:[{id:"hy-one",protocol:"hysteria2",port:20001,udp_ports:["31001:31002"],tls:{enabled:true,server_name:"example.test"}},{id:"hy-two",protocol:"hysteria2",port:20002,udp_ports:["32001:32002"],tls:{enabled:true}}]},certificates:[{id:"draft",provider:"acme",domain:"draft.example.test"}]};
const controller = new AbortController();
const ctx = {config:async()=>config,signal:controller.signal,changed(){},render(){},task(value){tasks.push(value);},request:async()=>[{id:"live",domain:"live.example.test",provider:"acme",saved:false,applied:true,pending:true,can_renew:true,used_by:["入站（已生效）"],days_left:-2,renewal_state:"automatic"}]};
const content = document.querySelector("main");
content.replaceChildren(...await certificates(ctx));
const rowFor = id => [...content.querySelectorAll("tbody tr")].find(row => row.textContent.includes(id));
const draft = rowFor("draft"), live = rowFor("live");
assert.ok(draft && live, "draft and applied-only certificate must remain visible");
const renew = row => [...row.querySelectorAll("button")].find(button=>button.textContent === "申请 / 续期");
assert.equal(renew(draft).disabled,true);
assert.match(draft.textContent,/请先应用/);
renew(draft).click();
assert.equal(tasks.length,0);
assert.equal(renew(live).disabled,false);
assert.match(live.textContent,/已过期 2 天/);
assert.equal([...live.querySelectorAll("button")].some(button=>button.textContent.includes("移除")),false);
renew(live).click();
assert.deepEqual(tasks,[{operation:"certificate-renew",id:"live"}]);
content.replaceChildren(...await inbounds(ctx));
const second = rowFor("hy-two");
assert.match(second.textContent,/32001:32002/);
[...second.querySelectorAll("button")].find(button=>button.textContent === "编辑").click();
const dialog = document.querySelector("dialog");
assert.match(dialog.textContent,/额外 UDP 端口|UDP 跳跃端口/);
assert.match(dialog.textContent,/当前入站/);
assert.equal(config.app.nodes[0].udp_ports[0],"31001:31002");
assert.equal(config.app.nodes[1].udp_ports[0],"32001:32002");
controller.abort();
dom.window.close();
console.log("Recovery UI passed: unapplied renewal disabled, live assets retained, expired dates and per-inbound UDP ownership.");
