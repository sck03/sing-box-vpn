#!/usr/bin/env python3
"""Refresh linked Go module notices after updating go.mod (requires Go)."""
import json
import os
from pathlib import Path
import shutil
import subprocess

root = Path(__file__).resolve().parent.parent
modules = {}
decoder = json.JSONDecoder()
for target in ("windows", "linux"):
    env = dict(os.environ, GOOS=target, GOARCH="amd64", CGO_ENABLED="0")
    raw = subprocess.check_output([
        "go", "list", "-deps", "-json", "-tags", "with_quic,with_utls,with_wireguard",
        "./addons/vpngate/gateway", "./cmd/managed-core",
    ], cwd=root, env=env, text=True, encoding="utf-8")
    while raw.strip():
        value, end = decoder.raw_decode(raw.lstrip())
        raw = raw.lstrip()[end:]
        module = value.get("Module", {})
        if module and not module.get("Main"):
            module = module.get("Replace", module)
            modules[module["Path"]] = module

destination = root / "third_party" / "modules"
lines = ["# Linked Go module notices", "", "Generated by `scripts/update-notices.py` for Linux and Windows with QUIC, uTLS and WireGuard enabled. Exact versions are pinned in go.mod/go.sum.", ""]
for name, module in sorted(modules.items()):
    target = destination / name.replace("/", "_")
    target.mkdir(parents=True, exist_ok=True)
    files = []
    for source in sorted(Path(module["Dir"]).iterdir()):
        if source.is_file() and source.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "COPYRIGHT", "NOTICE", "AUTHORS", "APACHE", "MIT-LICENSE")):
            shutil.copyfile(source, target / source.name)
            files.append(source.name)
    # YAML references the Apache text; retain the separately provided copy.
    if name == "go.yaml.in/yaml/v3" and (target / "APACHE-2.0.txt").exists() and "APACHE-2.0.txt" not in files:
        files.append("APACHE-2.0.txt")
    if not files:
        raise RuntimeError(f"Missing license: {name}")
    lines.append(f"- {name} {module['Version']}: {', '.join(files)}")
(destination / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Preserved notices for {len(modules)} linked modules.")
